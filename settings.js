export function languageLabel(code) {
  const needle = String(code || "").trim().toLowerCase();
  if (!needle) return "";
  for (const [value, label] of TRANSLATE_LANGUAGES) {
    if (value.toLowerCase() === needle) return label;
  }
  return String(code || "").trim();
}

export function filterLanguages(query) {
  const q = String(query || "")
    .trim()
    .toLowerCase();
  if (!q) return TRANSLATE_LANGUAGES.slice();
  return TRANSLATE_LANGUAGES.filter(([code, label]) => {
    return label.toLowerCase().includes(q) || code.toLowerCase().includes(q);
  });
}

export const DEFAULT_SETTINGS = {
  enabled: true,
  incoming: "en",
  outgoing: "ja",
};

const STORAGE_KEY = "discordTranslateSettings";

export function normalizeLanguageCode(code) {
  const raw = String(code || "").trim();
  if (!raw) return "";
  if (raw.toLowerCase() === "auto") return "auto";
  return raw;
}

function normalizeSettings(raw = {}) {
  const merged = { ...DEFAULT_SETTINGS, ...raw };
  merged.incoming =
    normalizeLanguageCode(raw.incoming ?? raw.language) || DEFAULT_SETTINGS.incoming;
  merged.outgoing = normalizeLanguageCode(raw.outgoing) || DEFAULT_SETTINGS.outgoing;
  delete merged.language;
  delete merged.targetLanguage;
  delete merged.myLanguage;
  return merged;
}

export async function getSettings() {
  const stored = await browser.storage.local.get(STORAGE_KEY);
  return normalizeSettings(stored[STORAGE_KEY] || {});
}

export async function saveSettings(patch) {
  const next = normalizeSettings({ ...(await getSettings()), ...patch });
  if (patch.incoming != null) next.incoming = normalizeLanguageCode(patch.incoming);
  if (patch.outgoing != null) next.outgoing = normalizeLanguageCode(patch.outgoing);
  await browser.storage.local.set({ [STORAGE_KEY]: next });
  return next;
}

export function toApiLang(code) {
  const raw = normalizeLanguageCode(code);
  if (!raw || raw.toLowerCase() === "auto") return "";
  const lower = raw.toLowerCase();
  if (lower === "zh" || lower === "zh-hans") return "zh-CN";
  if (lower === "zh-hant") return "zh-TW";
  if (lower === "he") return "iw";
  if (lower === "jv") return "jw";
  if (lower === "fil") return "tl";
  return raw;
}
